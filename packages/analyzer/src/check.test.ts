import { cp, mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { cruise } from 'dependency-cruiser';
import {
  applyOps,
  createCatalog,
  dataOwners,
  databaseViewOps,
  newProject,
  selectSuggestions,
} from '@archguide/core';
import type { Project } from '@archguide/core';
import { GENERATORS, profile } from '@archguide/profile-react-node-postgres';
import { analyzeRepository, checkRepository, githubAnnotations } from '.';

const catalog = createCatalog([profile]);
const fixtures = join(dirname(fileURLToPath(import.meta.url)), '..', 'fixtures');
const gen = (id: string) => GENERATORS.find((g) => g.id === id)!;

/** A copy of a fixture and its analyzed model, as `init` + `analyze --write` leave it. */
async function modeled(name: string, packs: string[] = []) {
  const root = await mkdtemp(join(tmpdir(), `archguide-${name}-`));
  await cp(join(fixtures, name), root, { recursive: true });
  let project = (newProject(catalog, { name }) as { project: Project }).project;
  const r = await analyzeRepository(root, { catalog, model: project.model });
  const applied = applyOps(
    project,
    [
      ...selectSuggestions(r.diff!),
      { op: 'updateSettings', patch: { rulePacks: [...project.settings.rulePacks, ...packs] } },
    ],
    catalog,
  );
  if (!applied.ok) throw new Error(JSON.stringify(applied.errors));
  project = applied.project;
  return { root, project };
}

describe('enforcement generators', () => {
  it('dependency-cruiser: a config file that dependency-cruiser loads and enforces as it is', async () => {
    const { root, project } = await modeled('bad-practices');
    const out = gen('dependency-cruiser').generate(project, {
      catalog,
      projectPath: 'architecture/x.archguide.json',
    });
    expect(out.content).toMatch(
      /^\/\/ Generated by archguide from architecture\/x\.archguide\.json/,
    );
    expect(out.rules).toEqual(
      expect.arrayContaining([
        'AG-RNP-003-no-db-client-in-app-web',
        'AG-RNP-006-domain-no-infra-dom-domain',
        'AG-RNP-013-fsd-shared-app-web',
        'AG-RNP-014-feature-isolation-app-web',
        'AG-no-circular',
      ]),
    );
    const file = join(root, 'dependency-cruiser.cjs');
    await writeFile(file, out.content);
    const config = createRequire(import.meta.url)(file) as {
      forbidden: unknown[];
      options: object;
    };
    const result = await cruise(['.'], {
      baseDir: root,
      validate: true,
      ruleSet: { forbidden: config.forbidden } as never,
      ...config.options,
    } as never);
    const names = (
      result.output as { summary: { violations: { rule: { name: string } }[] } }
    ).summary.violations.map((v) => v.rule.name);
    expect(names).toEqual(
      expect.arrayContaining([
        'AG-RNP-003-no-db-client-in-app-web',
        'AG-RNP-006-domain-no-infra-dom-domain',
        'AG-no-circular',
      ]),
    );
  });

  it('strict packs: imports between sibling parts that the model does not connect are forbidden', async () => {
    const { project } = await modeled('bad-practices', ['modular-monolith']);
    const rules = gen('dependency-cruiser').generate(project, { catalog, projectPath: 'p' }).rules;
    expect(rules).toEqual(
      expect.arrayContaining([
        'AG-mod-pricing-not-mod-discounts',
        'AG-mod-discounts-not-mod-pricing',
      ]),
    );
  });

  it('Nx and ArchUnitTS', async () => {
    const { project } = await modeled('pnpm-bff-pgboss');
    const nx = JSON.parse(gen('nx').generate(project, { catalog, projectPath: 'p' }).content) as {
      projects: Record<string, { tags: string[] }>;
      depConstraints: {
        sourceTag: string;
        onlyDependOnLibsWithTags: string[];
        bannedExternalImports?: string[];
      }[];
    };
    expect(nx.projects['services/bff']!.tags).toEqual(['scope:bff.bff', 'type:app']);
    expect(
      nx.depConstraints.find((d) => d.sourceTag === 'scope:bff.bff')?.onlyDependOnLibsWithTags,
    ).toEqual(['scope:api.contracts']);
    expect(
      nx.depConstraints.find((d) => d.sourceTag === 'scope:app.web')?.bannedExternalImports,
    ).toContain('@prisma/client');
    const domain = await modeled('bad-practices', ['modular-monolith']);
    const spec = gen('archunit').generate(domain.project, { catalog, projectPath: 'p' }).content;
    expect(spec).toContain("import { projectFiles } from 'archunit';");
    expect(spec).toContain(
      `projectFiles().inFolder("services/orders/src/modules/pricing/**").shouldNot().dependOnFiles().inFolder("services/orders/src/modules/discounts/**")`,
    );
    expect(spec).toContain('.should().haveNoCycles()');
  });
});

describe('archguide check', () => {
  it('fails on a domain → Prisma import seeded into a clean repository, with file and line', async () => {
    const { root, project } = await modeled('vite-express-prisma', ['hexagonal']);
    // A clean domain folder gets modeled; then someone imports the ORM into it.

    await mkdir(join(root, 'services/api/src/domain'), { recursive: true });
    await writeFile(
      join(root, 'services/api/src/domain/order.ts'),
      'export const statuses = ["new", "paid"];\n',
    );
    const withDomain = await analyzeRepository(root, { catalog, model: project.model });
    const next = applyOps(project, selectSuggestions(withDomain.diff!), catalog);
    if (!next.ok) throw new Error(JSON.stringify(next.errors));
    expect(next.project.model.elements.find((e) => e.kind === 'node.domain')?.codePaths).toEqual([
      'services/api/src/domain',
    ]);

    await writeFile(
      join(root, 'services/api/src/domain/order.ts'),
      'export const statuses = ["new", "paid"];\nimport { Prisma } from "@prisma/client";\nexport type Money = Prisma.Decimal;\n',
    );
    const report = await checkRepository(root, {
      catalog,
      project: next.project,
      projectPath: 'p',
    });
    expect(report.failed).toBe(true);
    const hit = report.items.find((i) => i.ruleId.startsWith('AG-RNP-006'));
    expect(hit).toMatchObject({
      severity: 'error',
      source: 'dependency-cruiser',
      file: 'services/api/src/domain/order.ts',
      line: 2,
    });
    expect(githubAnnotations(report)).toMatch(
      /::error file=services\/api\/src\/domain\/order\.ts,line=2,title=AG-RNP-006-domain-no-infra-dom-domain::/,
    );
    // The analysis rule sees it too.
    expect(report.items.find((i) => i.ruleId === 'RNP-006')).toMatchObject({
      file: 'services/api/src/domain/order.ts',
      line: 2,
    });
  });

  it('passes a clean, modeled repository, and leaves suppressed findings out', async () => {
    const { root, project } = await modeled('pnpm-bff-pgboss');
    const report = await checkRepository(root, { catalog, project, projectPath: 'p' });
    expect(report.errors).toEqual([]);
    expect(report.items.filter((i) => i.severity === 'error')).toEqual([]);
    expect(report.failed).toBe(false);
    const warned = report.items.find((i) => i.source === 'analysis')!;
    const suppressed = applyOps(
      project,
      [
        {
          op: 'upsertSuppression',
          suppression: {
            ruleId: warned.ruleId,
            targetIds: warned.targetIds,
            reason: 'Accepted for the first release.',
            createdAt: '2026-10-28T00:00:00.000Z',
          },
        },
      ],
      catalog,
    );
    if (!suppressed.ok) throw new Error('suppression');
    const again = await checkRepository(root, {
      catalog,
      project: suppressed.project,
      projectPath: 'p',
    });
    expect(
      again.items.some(
        (i) => i.ruleId === warned.ruleId && i.targetIds.join() === warned.targetIds.join(),
      ),
    ).toBe(false);
  });
});

describe('data ownership in the model (database view)', () => {
  it('names the owner of each schema and flags data written by others', async () => {
    const { project } = await modeled('pnpm-bff-pgboss');
    const owners = dataOwners(project, catalog);
    expect(owners.get('schema.orders')).toMatchObject({
      owner: 'svc.orders',
      writers: ['svc.orders'],
      shared: false,
    });
    expect(owners.get('tbl.event')).toMatchObject({ owner: 'svc.catalog', shared: false });
    const bad = (await modeled('bad-practices')).project;
    // Two migration owners: nobody owns public, and two services write it.
    expect(dataOwners(bad, catalog).get('schema.public')).toMatchObject({
      writers: ['svc.billing', 'svc.orders'],
      shared: true,
    });
  });

  it('builds a database view with the data and its readers and writers only', async () => {
    const { project } = await modeled('pnpm-bff-pgboss');
    const { ops, viewId } = databaseViewOps(project, catalog);
    const r = applyOps(project, ops, catalog);
    if (!r.ok) throw new Error(JSON.stringify(r.errors));
    const view = r.project.views.find((v) => v.id === viewId)!;
    expect(view.kind).toBe('database');
    const shown = view.nodes.map((n) => n.elementId);
    expect(shown).toEqual(
      expect.arrayContaining([
        'tbl.ticket-order',
        'schema.catalog',
        'svc.orders',
        'svc.catalog',
        'wrk.mailer',
      ]),
    );
    expect(shown).not.toContain('app.web');
    expect(shown).not.toContain('bff.bff');
    expect(view.edges.length).toBeGreaterThan(0);
  });
});
