// Writes docs/RULES.md from the rule metadata (generic rules + this profile's rules).
// `--check` fails when the committed file is out of date (used in CI).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_RULE_PACKS, RULE_PACKS, allRules, createCatalog } from '@archguide/core';
import type { Rule } from '@archguide/core';
import { PROFILE_ID, profile } from '../src';

const target = fileURLToPath(new URL('../../../../docs/RULES.md', import.meta.url));

const rules = allRules(createCatalog([profile]));
const byId = new Map(rules.map((r) => [r.id, r]));
const replacedBy = new Map<string, string>();
for (const r of rules) for (const id of r.replaces ?? []) replacedBy.set(id, r.id);

const packName = (id: string) =>
  id === PROFILE_ID
    ? `${profile.name} (always on)`
    : (RULE_PACKS.find((p) => p.id === id)?.name ?? id);

const anchor = (id: string) => `#${id.toLowerCase()}`;
const ruleLink = (id: string) => (byId.has(id) ? `[${id}](${anchor(id)})` : id);

function section(rule: Rule): string {
  const lines = [
    `### ${rule.id}`,
    '',
    `**${rule.title}** · ${rule.severity} · packs: ${rule.packs.map(packName).join(', ')}`,
    '',
    rule.rationale,
  ];
  const notes: string[] = [];
  if (rule.replaces?.length)
    notes.push(`Replaces ${rule.replaces.map(ruleLink).join(', ')} for this stack.`);
  const by = replacedBy.get(rule.id);
  if (by) notes.push(`With the ${profile.name} profile, ${ruleLink(by)} runs instead.`);
  if (rule.learnId) notes.push(`Learn: \`${rule.learnId}\`.`);
  if (notes.length) lines.push('', notes.join(' '));
  return lines.join('\n');
}

const generic = rules.filter((r) => r.id.startsWith('AP-'));
const specific = rules.filter((r) => !r.id.startsWith('AP-'));

const text = `<!-- Generated by packages/profiles/react-node-postgres/scripts/build-rules-doc.ts. Do not edit; run \`pnpm rules-doc\`. -->

# Rules

Rules find anti-patterns in a model. Each finding names the elements or relations it is
about, says why it matters, and may offer quick fixes. A finding can be suppressed with a
reason. See Implementation.md §11 for the engine.

## Rule packs

A rule runs when one of its packs is on. \`core\` and the project's profile are always on;
new projects start with: ${DEFAULT_RULE_PACKS.map((p) => `\`${p}\``).join(', ')}.

| Pack | Name | What it checks |
| --- | --- | --- |
${RULE_PACKS.map((p) => `| \`${p.id}\` | ${p.name} | ${p.description} |`).join('\n')}

## Summary

| Rule | Title | Severity | Packs |
| --- | --- | --- | --- |
${rules.map((r) => `| ${ruleLink(r.id)} | ${r.title} | ${r.severity} | ${r.packs.join(', ')} |`).join('\n')}

## Generic rules

${generic.map(section).join('\n\n')}

## ${profile.name} rules

${specific.map(section).join('\n\n')}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // Missing file counts as out of date.
  }
  if (current !== text) {
    console.error('docs/RULES.md is out of date. Run: pnpm rules-doc');
    process.exit(1);
  }
  console.log(`docs/RULES.md is up to date (${rules.length} rules).`);
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, text);
  console.log(`Wrote ${target} (${rules.length} rules).`);
}
